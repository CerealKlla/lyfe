package com.github.cerealklla.lyfe.socket;

import java.lang.reflect.Constructor;
import java.lang.reflect.Field;
import java.util.ArrayList;
import java.util.List;
import java.util.Optional;

import net.minecraft.resources.Identifier;
import net.minecraft.util.context.ContextKeySet;
import net.minecraft.world.level.storage.loot.LootPool;
import net.minecraft.world.level.storage.loot.LootTable;
import net.minecraft.world.level.storage.loot.functions.LootItemFunction;

/**
 * Shared reflective "append to an already-loaded {@link LootTable}" helper -- factored out of {@code
 * loot.ResearchNoteLootInjector}'s own identical technique (confirmed there, 2026-10-03, that no
 * public API adds a pool/function to an already-built table: {@code LootTable.Builder} only accepts
 * pool *builders*, and both {@code pools}/{@code functions} are private fields with no accessor).
 * Widened here (2026-10-18, Rune loot) to also support appending a table-level {@code
 * LootItemFunction} (applies to every item ANY pool in the table generates), not just a whole extra
 * pool -- {@code socket.PreSocketedGearInjector} needs that shape, since it must run against items
 * generated by the table's own EXISTING entries, not add a new one.
 */
final class LootTableReflection {

    private static final Field PARAM_SET_FIELD;
    private static final Field RANDOM_SEQUENCE_FIELD;
    private static final Field POOLS_FIELD;
    private static final Field FUNCTIONS_FIELD;
    private static final Constructor<LootTable> CONSTRUCTOR;

    static {
        try {
            PARAM_SET_FIELD = LootTable.class.getDeclaredField("paramSet");
            PARAM_SET_FIELD.setAccessible(true);
            RANDOM_SEQUENCE_FIELD = LootTable.class.getDeclaredField("randomSequence");
            RANDOM_SEQUENCE_FIELD.setAccessible(true);
            POOLS_FIELD = LootTable.class.getDeclaredField("pools");
            POOLS_FIELD.setAccessible(true);
            FUNCTIONS_FIELD = LootTable.class.getDeclaredField("functions");
            FUNCTIONS_FIELD.setAccessible(true);
            CONSTRUCTOR = LootTable.class.getDeclaredConstructor(
                    ContextKeySet.class, Optional.class, List.class, List.class);
            CONSTRUCTOR.setAccessible(true);
        } catch (ReflectiveOperationException e) {
            throw new ExceptionInInitializerError(e);
        }
    }

    private LootTableReflection() {
    }

    @SuppressWarnings("unchecked")
    static LootTable withExtraPool(LootTable table, LootPool extra) {
        try {
            ContextKeySet paramSet = (ContextKeySet) PARAM_SET_FIELD.get(table);
            Optional<Identifier> randomSequence = (Optional<Identifier>) RANDOM_SEQUENCE_FIELD.get(table);
            List<LootPool> pools = new ArrayList<>((List<LootPool>) POOLS_FIELD.get(table));
            pools.add(extra);
            List<LootItemFunction> functions = (List<LootItemFunction>) FUNCTIONS_FIELD.get(table);
            return CONSTRUCTOR.newInstance(paramSet, randomSequence, pools, functions);
        } catch (ReflectiveOperationException e) {
            // Best-effort -- if this version's LootTable shape ever changes underneath us, skip
            // rather than crash loot generation for every table in the game.
            return table;
        }
    }

    @SuppressWarnings("unchecked")
    static LootTable withExtraFunction(LootTable table, LootItemFunction extra) {
        try {
            ContextKeySet paramSet = (ContextKeySet) PARAM_SET_FIELD.get(table);
            Optional<Identifier> randomSequence = (Optional<Identifier>) RANDOM_SEQUENCE_FIELD.get(table);
            List<LootPool> pools = (List<LootPool>) POOLS_FIELD.get(table);
            List<LootItemFunction> functions = new ArrayList<>((List<LootItemFunction>) FUNCTIONS_FIELD.get(table));
            functions.add(extra);
            return CONSTRUCTOR.newInstance(paramSet, randomSequence, pools, functions);
        } catch (ReflectiveOperationException e) {
            return table;
        }
    }
}
